/// Response from GET /sessions/:id/status.
#[derive(Debug, Serialize, Deserialize)]
pub struct SessionStatusResponse {
    pub state: SessionState,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub abort_signal: Option<String>,
}

/// Serialise released output as its receipt v3 canonical (RFC 8785) text, so
/// the delivered bytes are exactly the bytes the receipt's `output_hash`
/// commits to.
fn serialize_canonical_output<S: serde::Serializer>(
    value: &serde_json::Value,
    serializer: S,
) -> Result<S::Ok, S::Error> {
    use serde::ser::Error;
    let text = receipt_core::canonicalize_v3(value).map_err(S::Error::custom)?;
    let raw = serde_json::value::RawValue::from_string(text).map_err(S::Error::custom)?;
    raw.serialize(serializer)
}

fn serialize_canonical_output_opt<S: serde::Serializer>(
    value: &Option<serde_json::Value>,
    serializer: S,
) -> Result<S::Ok, S::Error> {
    match value {
        Some(v) => serialize_canonical_output(v, serializer),
        None => serializer.serialize_none(),
    }
}

/// Response from GET /sessions/:id/output.
#[derive(Debug, Serialize, Deserialize)]
pub struct SessionOutputResponse {
    pub state: SessionState,
    /// Released output, serialised as its canonical text.
    #[serde(
        default,
        skip_serializing_if = "Option::is_none",
        serialize_with = "serialize_canonical_output_opt"
    )]
    pub output: Option<serde_json::Value>,
    /// Signed v3 receipt (success or failure), once the session is terminal.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub receipt: Option<receipt_core::ReceiptV3>,
}

// ============================================================================
// Echo mode types (backward compatibility)
// ============================================================================

/// Echo-mode response from POST /sessions/:id/input (after both inputs received).
#[derive(Debug, Serialize, Deserialize)]
pub struct EchoResponse {
    pub session_id: String,
    /// v3 input commitment (`SHA256_N32_JCS_V3`) to the initiator's decrypted
    /// input. Each party checks its own entry with its nonce and context.
    pub initiator_input_commitment: String,
    /// v3 input commitment to the responder's decrypted input.
    pub responder_input_commitment: String,
    pub tee_attestation: EchoTeeAttestation,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct EchoTeeAttestation {
    pub tee_type: String,
    pub measurement: String,
    pub attestation_hash: String,
    pub receipt_signing_pubkey_hex: String,
    pub transcript_hash_hex: String,
}
